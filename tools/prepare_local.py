"""Generate missing local pairing configuration and rasterize the boot font.

Uses existing Python + Pillow; creates no environment and never replaces tokens.
"""
from pathlib import Path
import json
import secrets
from PIL import Image, ImageDraw, ImageFont

root = Path(__file__).resolve().parents[1]
host = Path(r"C:\Users\10145294\Documents\MySoftware\Moonlight_S3_Host")
secret = root / "include/config_secrets.h"
if not secret.exists():
    token = secrets.token_hex(16)
    secret.write_text('#pragma once\n#define MOONLIGHT_PAIRING_TOKEN "' + token + '"\n')
else:
    token = secret.read_text().split('"')[1]
settings = host / "settings.json"
if not settings.exists():
    settings.write_text(json.dumps(dict(host="", port=47989, token=token,
        monitor=1, quality=60, fps=25, resolution="400x240", control=True, toolbar=True), indent=2))
font = ImageFont.load_default(size=12)
rows = []
for char in range(32,127):
    im = Image.new("1", (8,16))
    ImageDraw.Draw(im).text((0,0), chr(char), font=font, fill=1)
    rows.append("{" + ",".join(str(sum((1 << (7-x)) for x in range(8) if im.getpixel((x,y)))) for y in range(16)) + "}")
(root / "include/font.h").write_text("#pragma once\n// Rasterized Pillow default font, generated by tools/prepare_local.py.\nstatic const uint8_t Font[95][16]={\n" + ",\n".join(rows) + "\n};\n")
print("Local pairing config and boot font ready; existing credentials preserved.")
